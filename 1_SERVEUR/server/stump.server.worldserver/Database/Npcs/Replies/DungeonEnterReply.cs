    /// <summary>
    /// Generic dungeon keeper entry, one row per dungeon entrance map.
    /// </summary>
    [TableName("dungeons_entries")]
    public class DungeonEntryRecord : IAutoGeneratedRecord
    {
        [PrimaryKey("Id")]
        public int Id { get; set; }

        public int DungeonId { get; set; }

        public int EntranceMapId { get; set; }

        public int KeyItemId { get; set; }

        public int FirstRoomMapId { get; set; }

        public int FirstRoomCellId { get; set; }

        /// <summary>NEKFEU : case du gardien ; sert a choisir le donjon quand plusieurs entrees partagent la meme map (Tofus / Tofu Royal).</summary>
        public int KeeperCellId { get; set; }
    }

    /// <summary>
    /// "Donner la clé et entrer dans le donjon" : the dungeon is found from the map the keeper stands on,
    /// the key (when the dungeon has one) is consumed and the player is sent to the first room.
    /// </summary>
    [Discriminator("DungeonEnter", typeof(NpcReply), typeof(NpcReplyRecord))]
    public class DungeonEnterReply : NpcReply
    {
        static Dictionary<int, DungeonEntryRecord[]> m_entries;

        public DungeonEnterReply(NpcReplyRecord record)
            : base(record)
        {
        }

        internal static DungeonEntryRecord GetEntry(Npc npc, NpcReplyRecord reponse = null)
        {
            if (m_entries == null)
                m_entries = WorldServer.Instance.DBAccessor.Database.Query<DungeonEntryRecord>("SELECT * FROM dungeons_entries")
                    .GroupBy(x => x.EntranceMapId).ToDictionary(x => x.Key, x => x.ToArray());

            if (npc?.Map == null || !m_entries.TryGetValue(npc.Map.Id, out var entries))
                return null;

            // MYSTIC 17/10 : un même gardien pour deux donjons (Bibiblop : Clos des Blops / Blop Multicolore) -> le donjon est
            // indiqué dans Parameter0 de la réponse
            string param = null;
            try
            {
                param = reponse?.GetParameter<string>(0, true);
            }
            catch
            {
            }
            if (int.TryParse(param, out var dungeonId) && dungeonId > 0)
            {
                var choisi = entries.FirstOrDefault(x => x.DungeonId == dungeonId);
                if (choisi != null)
                    return choisi;
            }

            // NEKFEU : plusieurs donjons sur la meme map -> celui dont le gardien est sur la case du PNJ
            return entries.FirstOrDefault(x => npc.Cell != null && x.KeeperCellId == npc.Cell.Id) ?? entries[0];
        }

        // NEKFEU : la reponse n'apparait que sur une map d'entree (Lorkos a le meme dialogue partout dans le labyrinthe)
        public override bool CanShow(Npc npc, Character character) =>
            base.CanShow(npc, character) && GetEntry(npc, Record) != null;

        public override bool Execute(Npc npc, Character character)
        {
            if (!base.Execute(npc, character))
                return false;

            var entry = GetEntry(npc, Record);
            var room = entry == null ? null : Game.World.Instance.GetMap(entry.FirstRoomMapId);
            if (room == null)
            {
                character.SendServerMessage("Ce donjon n'est pas accessible pour le moment.");
                return false;
            }

            if (entry.KeyItemId > 0)
            {
                var template = ItemManager.Instance.TryGetTemplate(entry.KeyItemId);
                var key = template == null ? null : character.Inventory.TryGetItem(template);
                if (key == null)
                {
                    character.SendServerMessage($"Il vous faut la clé pour entrer : {template?.Name ?? "clé du donjon"}.");
                    return false;
                }

                character.Inventory.RemoveItem(key, 1);
                character.SendInformationMessage(TextInformationTypeEnum.TEXT_INFORMATION_MESSAGE, 22, 1, template.Id);
            }

            var cell = room.GetUsableCell(entry.FirstRoomCellId);

            return character.Teleport(room, cell);
        }
    }

    /// <summary>
    /// MYSTIC : « Utiliser le trousseau de clefs » (réponse officielle du client chez 81 gardiens, ajoutée par
    /// _OUTILS/serveur/trousseau/reponses_trousseau.sql). Visible seulement si le trousseau a encore la clef de ce donjon ;
    /// la clef du trousseau est alors utilisée (une fois par donjon, retour 7 jours après la première), la vraie clef est gardée.
    /// </summary>
    [Discriminator("DungeonEnterTrousseau", typeof(NpcReply), typeof(NpcReplyRecord))]
    public class DungeonEnterTrousseauReply : NpcReply
    {
        public DungeonEnterTrousseauReply(NpcReplyRecord record)
            : base(record)
        {
        }

        public override bool CanShow(Npc npc, Character character)
        {
            if (!base.CanShow(npc, character))
                return false;

            var entry = DungeonEnterReply.GetEntry(npc, Record);
            return entry != null && entry.KeyItemId > 0 && Game.Items.Player.Custom.TrousseauManager.Instance.CanUse(character, entry.DungeonId);
        }

        public override bool Execute(Npc npc, Character character)
        {
            if (!base.Execute(npc, character))
                return false;

            var entry = DungeonEnterReply.GetEntry(npc, Record);
            var room = entry == null ? null : Game.World.Instance.GetMap(entry.FirstRoomMapId);
            if (room == null)
            {
                character.SendServerMessage("Ce donjon n'est pas accessible pour le moment.");
                return false;
            }

            if (entry.KeyItemId <= 0 || !Game.Items.Player.Custom.TrousseauManager.Instance.TryUse(character, entry.DungeonId))
            {
                character.SendServerMessage("Votre trousseau n'a plus la clef de ce donjon.");
                return false;
            }

            character.SendServerMessage("Trousseau de clefs : clef de ce donjon utilisée (elle revient avec les autres au bout de 7 jours).");
            return character.Teleport(room, room.GetUsableCell(entry.FirstRoomCellId));
        }
    }

    /// <summary>
    /// MYSTIC 17/10 : « Reprendre le donjon où vous l'avez quitté » (réponse officielle des gardiens) : visible si le personnage a
    /// une salle sauvegardée dans ce donjon (RepriseDonjons) ; l'y ramène gratuitement.
    /// </summary>
    [Discriminator("DungeonResume", typeof(NpcReply), typeof(NpcReplyRecord))]
    public class DungeonResumeReply : NpcReply
    {
        public DungeonResumeReply(NpcReplyRecord record)
            : base(record)
        {
        }

        public override bool CanShow(Npc npc, Character character)
        {
            if (!base.CanShow(npc, character))
                return false;

            var entry = DungeonEnterReply.GetEntry(npc, Record);
            return entry != null && Game.Donjons.RepriseDonjons.Instance.Obtenir(character, entry.DungeonId) != null;
        }

        public override bool Execute(Npc npc, Character character)
        {
            if (!base.Execute(npc, character))
                return false;

            var entry = DungeonEnterReply.GetEntry(npc, Record);
            var sauvegarde = entry == null ? null : Game.Donjons.RepriseDonjons.Instance.Obtenir(character, entry.DungeonId);
            var salle = sauvegarde == null ? null : Game.World.Instance.GetMap(sauvegarde.Value.carte);
            if (salle == null)
            {
                character.SendServerMessage("Aucune salle à reprendre dans ce donjon.");
                return false;
            }

            return character.Teleport(salle, salle.GetUsableCell(sauvegarde.Value.cellule));
        }
    }
}
