using System.Collections.Generic;
using System.Linq;
using Stump.DofusProtocol.Enums;
using Stump.ORM;
using Stump.ORM.SubSonic.SQLGeneration.Schema;
using Stump.Server.BaseServer.Database;
using Stump.Server.WorldServer.Game.Actors.RolePlay.Characters;
using Stump.Server.WorldServer.Game.Actors.RolePlay.Npcs;

namespace Stump.Server.WorldServer.Database.Npcs.Replies
{
    /// <summary>
    /// NEKFEU : sortie d'un donjon depuis sa salle de fin, une ligne par salle de fin.
    /// </summary>
    [TableName("dungeons_exits")]
    public class DungeonExitRecord : IAutoGeneratedRecord
    {
        [PrimaryKey("Id")]
        public int Id { get; set; }

        public int DungeonId { get; set; }

        /// <summary>Map de la salle de fin (où se trouve le PNJ).</summary>
        public int EndMapId { get; set; }

        /// <summary>Destination « devant le donjon ».</summary>
        public int ExitMapId { get; set; }

        public int ExitCellId { get; set; }

        public int ExitDirection { get; set; }
    }

    /// <summary>
    /// NEKFEU : « Sortir du donjon » — la sortie est trouvée d'après la map où se trouve le joueur (salle de fin).
    /// Un même PNJ (même message) peut ainsi servir dans plusieurs donjons. Réponse visible seulement dans une salle de fin connue.
    /// </summary>
    [Discriminator("DungeonExit", typeof(NpcReply), typeof(NpcReplyRecord))]
    public class DungeonExitReply : NpcReply
    {
        static Dictionary<int, DungeonExitRecord> m_exits;

        public DungeonExitReply(NpcReplyRecord record)
            : base(record)
        {
        }

        static DungeonExitRecord GetExit(int mapId)
        {
            if (m_exits == null)
                m_exits = WorldServer.Instance.DBAccessor.Database.Query<DungeonExitRecord>("SELECT * FROM dungeons_exits")
                    .GroupBy(x => x.EndMapId).ToDictionary(x => x.Key, x => x.First());

            return m_exits.TryGetValue(mapId, out var exit) ? exit : null;
        }

        public override bool CanShow(Npc npc, Character character) =>
            base.CanShow(npc, character) && character.Map != null && GetExit(character.Map.Id) != null;

        public override bool Execute(Npc npc, Character character)
        {
            if (!base.Execute(npc, character))
                return false;

            var exit = character.Map == null ? null : GetExit(character.Map.Id);
            var map = exit == null ? null : Game.World.Instance.GetMap(exit.ExitMapId);
            if (map == null)
            {
                character.SendServerMessage("La sortie de ce donjon n'est pas disponible pour le moment.");
                return false;
            }

            var cell = map.GetUsableCell(exit.ExitCellId);

            return character.Teleport(new Game.Maps.Cells.ObjectPosition(map, cell, (DirectionsEnum)exit.ExitDirection));
        }
    }
}
