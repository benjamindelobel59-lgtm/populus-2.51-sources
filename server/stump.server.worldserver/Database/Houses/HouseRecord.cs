using System;
using Stump.ORM;
using Stump.ORM.SubSonic.SQLGeneration.Schema;
using Stump.Server.WorldServer.Game.Maps;

namespace Stump.Server.WorldServer.Database.Houses
{
    public class HouseRelator
    {
        public static string FetchQuery = "SELECT * FROM houses";
    }

    /// <summary>
    /// A player house : the door is an interactive (DoorElementId = interactive spawn id) on DoorMapId.
    /// </summary>
    [TableName("houses")]
    public sealed class HouseRecord : IAutoGeneratedRecord
    {
        Map m_doorMap;
        Map m_interiorMap;

        [PrimaryKey("Id")]
        public int Id { get; set; }

        public int DoorMapId { get; set; }

        [Ignore]
        public Map DoorMap => m_doorMap ?? (m_doorMap = Game.World.Instance.GetMap(DoorMapId));

        public int DoorElementId { get; set; }

        public int InteriorMapId { get; set; }

        [Ignore]
        public Map InteriorMap => m_interiorMap ?? (m_interiorMap = Game.World.Instance.GetMap(InteriorMapId));

        public int ModelId { get; set; }

        public long Price { get; set; }

        public int? OwnerId { get; set; }

        [NullString]
        public string OwnerName { get; set; }

        public DateTime? PurchaseDate { get; set; }

        public bool Locked { get; set; }

        public bool ForSale { get; set; }

        public long SalePrice { get; set; }
    }
}
